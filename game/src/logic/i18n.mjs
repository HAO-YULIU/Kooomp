let lang = (() => { try { return localStorage.getItem('ml_lang') || 'zh'; } catch { return 'zh'; } })();
export const getLang = () => lang;
export function setLang(l) { lang = l === 'en' ? 'en' : 'zh'; try { localStorage.setItem('ml_lang', lang); } catch { /* 無痕模式 */ } document.documentElement.lang = lang === 'en' ? 'en' : 'zh-Hant'; }
export function t(key, vars = {}) {
  const v = key.split('.').reduce((o, k) => o?.[k], TEXT[lang]) ?? key.split('.').reduce((o, k) => o?.[k], TEXT.zh) ?? key;
  return String(v).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
export const errText = (code, vars) => t(`err.${code}`, vars) === `err.${code}` ? t('err.network') : t(`err.${code}`, vars);
